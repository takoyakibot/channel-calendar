    <h1>プライバシーポリシー</h1>
    <p class="meta">最終更新日: 2026年9月15日</p>

    <p>Channel Calendar（以下「本サイト」）は、YouTube チャンネルの配信予定・配信履歴をカレンダー形式で表示する非公式の情報サイトです。本ポリシーでは、本サイトが取り扱う情報について説明します。</p>

    <h2>1. 訪問者から収集する情報</h2>
    <p>本サイトは、閲覧にあたって会員登録や個人情報の入力を求めません。アクセス解析ツールや広告配信も利用していません。</p>
    <ul>
        <li><strong>Cookie</strong>: サイトの動作（セッション管理・不正なフォーム送信の防止）のために、Laravel フレームワークが発行する Cookie（<code>laravel_session</code>、<code>XSRF-TOKEN</code>）を使用します。これらに個人を特定する情報は含まれません。</li>
        <li><strong>ブラウザ保存領域</strong>: 表示形式（週ボード／月）の選択を、お使いのブラウザの localStorage に保存します。この情報はサーバーへ送信されません。</li>
        <li><strong>アクセスログ</strong>: ホスティング事業者のサーバーが、IP アドレス・アクセス日時・ブラウザ種別などを一定期間記録する場合があります。障害対応・不正アクセス対策以外の目的には利用しません。</li>
    </ul>

    <h2>2. YouTube API Services の利用</h2>
    <p>本サイトは <strong>YouTube API Services</strong> を利用して、登録されたチャンネルの公開情報を取得しています。本サイトを利用することで、<a href="https://www.youtube.com/t/terms" target="_blank" rel="noopener noreferrer">YouTube 利用規約</a>および <a href="https://www.google.com/policies/privacy" target="_blank" rel="noopener noreferrer">Google プライバシーポリシー</a>に同意したものとみなされます。</p>
    <ul>
        <li><strong>取得する情報</strong>: チャンネル名・チャンネルアイコン・ハンドル、配信（動画）のタイトル・サムネイル・予定開始時刻・開始/終了時刻など、YouTube 上で公開されている情報のみです。</li>
        <li><strong>取得しない情報</strong>: 本サイトは Google アカウントへのアクセス許可（OAuth）を求めず、訪問者・視聴者・チャンネル運営者の非公開情報や個人情報を取得・保存しません。</li>
        <li><strong>保存と更新</strong>: 取得した情報は本サイトのデータベースに保存し、約30分ごとに YouTube から再取得して更新します。YouTube 上で削除・非公開になった配信は、次回の更新時に本サイトからも削除されます。</li>
        <li><strong>第三者への提供</strong>: 取得した情報を第三者に販売・提供することはありません。本サイト上での表示のみに利用します。</li>
    </ul>

    <h2>3. 管理者アカウント</h2>
    <p>本サイトの管理機能は運営者のみが利用します。管理者のメールアドレスと、ハッシュ化したパスワードを保存します。YouTube API キーは暗号化して保存します。</p>

    <h2>4. 外部リンク</h2>
    <p>本サイトの各配信は YouTube（youtube.com）へリンクしています。リンク先での情報の取り扱いは、それぞれのサイトのプライバシーポリシーに従います。</p>

    <h2>5. 掲載情報の削除</h2>
    <p>ご自身のチャンネルの掲載を望まない場合は、運営者までご連絡ください。確認のうえ速やかに掲載を停止します。</p>

    <h2>6. 本ポリシーの変更</h2>
    <p>本ポリシーは必要に応じて改定することがあります。改定後の内容は本ページに掲載した時点で効力を生じます。</p>
