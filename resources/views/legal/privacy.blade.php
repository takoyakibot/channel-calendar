    <h1>プライバシーポリシー</h1>
    <p class="meta">最終更新日: 2026年9月15日</p>

    <p>Channel Calendar（以下「本サイト」）は、YouTube チャンネルの配信予定・配信履歴をカレンダー形式で表示する非公式の情報サイトです。本ポリシーでは、本サイトが取り扱う情報について説明します。</p>

    <h2>1. 収集する情報</h2>

    <h3>1-1. すべての訪問者</h3>
    <ul>
        <li><strong>Cookie（必須）</strong>: サイトの動作に必要な Cookie（セッション管理用の <code>laravel_session</code>、CSRF 対策用の <code>XSRF-TOKEN</code>）を使用します。これらは本サイトの基本機能に不可欠であり、無効にすることはできません。</li>
        <li><strong>ブラウザ保存領域（localStorage）</strong>: 表示形式やチャンネルの表示・非表示設定をブラウザの localStorage に保存します。この情報はサーバーへ送信されません。</li>
        <li><strong>アクセスログ</strong>: ホスティング事業者のサーバーが、IP アドレス・アクセス日時・ブラウザ種別などを一定期間記録する場合があります。障害対応・不正アクセス対策以外の目的には利用しません。</li>
        <li><strong>アクセス解析（任意）</strong>: 利用状況の把握のため Google アナリティクス（Google LLC）を使用します。詳細は「<a href="#analytics">3. アクセス解析ツールについて</a>」をご覧ください。Cookie の使用に「すべて許可」で同意した場合にのみ有効になります。</li>
    </ul>

    <h3>1-2. Google アカウントでログインした場合</h3>
    <p>本サイトでは Google アカウントによるログイン機能を提供しています。ログインにより、以下の情報を取得・保存します。</p>
    <ul>
        <li><strong>取得する情報</strong>: Google アカウントの表示名、メールアドレス、プロフィール画像 URL、Google ID</li>
        <li><strong>利用目的</strong>:
            <ul>
                <li>ユーザーの識別とログイン状態の維持</li>
                <li>表示設定（非表示チャンネル・表示形式など）のサーバー側での保存</li>
                <li>手動予定の登録・管理</li>
                <li>管理者権限の判定（運営者が指定したメールアドレスとの照合）</li>
            </ul>
        </li>
        <li><strong>Cookie（任意）</strong>: ログイン状態を維持するための認証 Cookie を使用します。これらは Cookie の使用に同意し、ログインした場合にのみ設定されます。</li>
    </ul>

    <h2 id="cookie">2. Cookie について</h2>
    <p>本サイトでは、初回アクセス時に Cookie の使用について同意を求めます。</p>
    <ul>
        <li><strong>必須 Cookie</strong>: セッション管理・CSRF 対策に使用します。サイトの基本動作に必要なため、常に有効です。</li>
        <li><strong>任意 Cookie</strong>: ログイン状態の維持、および Google アナリティクスによるアクセス解析（<code>_ga</code> など）に使用します。「すべての Cookie を許可」に同意した場合にのみ設定されます。</li>
    </ul>
    <p>Cookie の同意設定は、各ページのフッターにある「Cookie 設定」から変更できます。「必要な Cookie のみ」を選択した場合、ログイン機能はご利用いただけず、アクセス解析も行われません。</p>

    <h2 id="analytics">3. アクセス解析ツールについて</h2>
    <p>本サイトは、Google LLC が提供する「Google アナリティクス」を利用して、ページの閲覧状況（閲覧ページ、参照元、ブラウザや端末の種類、おおよその地域など）を統計的に把握しています。</p>
    <ul>
        <li>Google アナリティクスは Cookie（<code>_ga</code> など）を使用してデータを収集します。IP アドレスは匿名化して送信され、収集されたデータに個人を特定する情報は含まれません。</li>
        <li>収集されたデータは Google のプライバシーポリシーに基づいて管理されます。詳しくは <a href="https://policies.google.com/privacy" target="_blank" rel="noopener noreferrer">Google のプライバシーポリシー</a>および <a href="https://policies.google.com/technologies/partner-sites" target="_blank" rel="noopener noreferrer">Google のサービスを使用するサイトやアプリから収集した情報の Google による使用</a>をご確認ください。</li>
        <li>解析は Cookie の使用に「すべて許可」で同意した場合にのみ開始されます。「必要な Cookie のみ」を選択するか、<a href="https://tools.google.com/dlpage/gaoptout" target="_blank" rel="noopener noreferrer">Google アナリティクス オプトアウト アドオン</a>を利用することで無効にできます。</li>
    </ul>

    <h2>4. 情報の保存と管理</h2>
    <ul>
        <li>ユーザー情報はサイトのデータベースに保存されます。</li>
        <li>パスワードは保存しません（Google 認証のみ）。</li>
        <li>YouTube API キーは暗号化して保存します。</li>
        <li>SSL/TLS による暗号化通信を使用します。</li>
    </ul>

    <h2>5. 第三者への提供</h2>
    <p>収集した情報を第三者に販売・提供することはありません。ただし、法令に基づく開示要求があった場合はこの限りではありません。</p>

    <h2>6. YouTube API Services の利用</h2>
    <p>本サイトは <strong>YouTube API Services</strong> を利用して、登録されたチャンネルの公開情報を取得しています。本サイトを利用することで、<a href="https://www.youtube.com/t/terms" target="_blank" rel="noopener noreferrer">YouTube 利用規約</a>および <a href="https://www.google.com/policies/privacy" target="_blank" rel="noopener noreferrer">Google プライバシーポリシー</a>に同意したものとみなされます。</p>
    <ul>
        <li><strong>取得する情報</strong>: チャンネル名・チャンネルアイコン・ハンドル、配信（動画）のタイトル・サムネイル・予定開始時刻・開始/終了時刻など、YouTube 上で公開されている情報のみです。</li>
        <li><strong>保存と更新</strong>: 取得した情報は本サイトのデータベースに保存し、定期的に YouTube から再取得して更新します。YouTube 上で削除・非公開になった配信は、次回の更新時に本サイトからも削除されます。</li>
    </ul>

    <h2>7. ユーザーの権利</h2>
    <ul>
        <li><strong>データの確認</strong>: ご自身のアカウント情報について、運営者にお問い合わせいただければ開示します。</li>
        <li><strong>データの削除</strong>: アカウントの削除を希望される場合は、運営者にご連絡ください。アカウントに紐づくすべてのデータ（表示設定・手動予定・操作ログ）を削除します。</li>
        <li><strong>チャンネル掲載の停止</strong>: ご自身のチャンネルの掲載を望まない場合は、運営者までご連絡ください。確認のうえ速やかに掲載を停止します。</li>
    </ul>

    <h2>8. 外部リンク</h2>
    <p>本サイトの各配信は YouTube（youtube.com）へリンクしています。リンク先での情報の取り扱いは、それぞれのサイトのプライバシーポリシーに従います。</p>

